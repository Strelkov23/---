const assert=require('node:assert/strict'),S=require('./site-search.js');
const rows=[{title:'Инвестиции в основной капитал',description:'Россия'},{title:'Основные фонды',description:'Инвестиции Россия'},{title:'Рынок труда',description:'Россия'}];
assert.deepEqual(S.find(rows,'инвестиции россия').map(r=>r.title),rows.slice(0,2).map(r=>r.title));
assert.equal(S.find(rows,'инвестиции труд').length,0);
assert.equal(S.find(rows,'').length,0);
assert.equal(S.norm(' ЁЛКА  '),'елка');
assert.equal(S.href('data-registry.html','id','a:b'),'data-registry.html?id=a%3Ab');
console.log('Site search tests passed');
const tools=[{title:'Карта',questions:['как сравнить регионы','посмотреть экономику на карте']},{title:'Рынок труда',questions:['сколько людей работает']},{title:'Сравнить регионы',description:'Региональные данные'}];
assert.equal(S.findTools(tools,'Как сравнить регионы?')[0].title,'Карта');
assert.equal(S.findTools(tools,'посмотреть экономику на карте')[0].title,'Карта');
assert.equal(S.findTools(tools,'сколько людей работает')[0].title,'Рынок труда');
assert.equal(S.findTools(tools,'несуществующий вопрос').length,0);
assert.equal(S.findTools(tools,'').length,0);
assert.equal(S.find(tools,'как сравнить регионы').length,0);
assert.equal(S.questionScore({questions:'invalid'},'invalid'),-1);
