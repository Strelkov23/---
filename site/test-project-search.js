const assert=require('node:assert/strict'),P=require('./project-search.js');
const spec=P.specs[0],data={edition:'2026-09-30',sha256:'a',rows:[{record:1,region:'Бурятия',name:'Завод Ёлка',investor:'АО Альфа',location:'Район',status:'реализуемый',cost_mln_rub:'0',jobs:0,edition:'2026-09-30',sha256:'a',sheet:'Лист',row:2,source:'https://example.org'},{record:2,region:'Бурятия',name:'Склад',cost_mln_rub:null,jobs:null,edition:'2026-09-30',sha256:'a'}]};
const ref={iso:'RU-BU',records:2,edition:data.edition,sha256:'a'};
const rows=P.records(spec,data,ref);
assert.equal(rows.length,2);
assert.equal(rows[0].cost,'0');
assert.equal(rows[0].jobs,0);
assert.equal(rows[1].sector,null);
assert.equal(P.select(rows,{query:'ЕЛКА альфа'}).length,1);
assert.equal(P.select(rows,{numeric:'both'}).length,1);
assert.equal(P.select(rows,{status:'__missing__'}).length,1);
assert.equal(P.select(rows,{sector:'__missing__'}).length,2);
assert.equal(P.select(rows,{iso:'RU-AMU'}).length,0);
assert.equal(P.select(rows,{status:'реализуемый'}).length,1);
assert.equal(P.select(rows,{query:'ничего'}).length,0);
assert.deepEqual(P.counts(rows)[0],{iso:'RU-BU',records:2,cost:1,jobs:1});
assert.throws(()=>P.records(spec,data,{...ref,sha256:'b'}));
assert.throws(()=>P.records(spec,data,{...ref,records:3}));
assert.throws(()=>P.records(spec,data,{...ref,edition:'2025-09-30'}));
assert.throws(()=>P.select(rows,{numeric:'unknown'}));
assert.deepEqual(P.records(spec,{edition:null,sha256:null,rows:[]},{iso:'RU-BU',edition:null,sha256:null,records:null}),[]);

assert.equal(P.decimalSum(['0.1','0.02','0.003']),'0.123');
assert.equal(P.decimalSum(['999999999999.99','0.01']),'1000000000000.00');
assert.equal(P.decimalSum([]),null);
assert.throws(()=>P.decimalSum(['-1']));
assert.throws(()=>P.decimalSum(['1e2']));
assert.deepEqual(P.numericSummary(rows,'RU-BU'),{iso:'RU-BU',records:2,costCount:1,jobsCount:1,both:1,cost:'0',jobs:'0'});
assert.equal(P.numericSummary(rows,'RU-AMU').cost,null);
assert.throws(()=>P.numericSummary(rows,''));

assert.equal(P.displayDecimal('0.005'),'0,01');
assert.equal(P.displayDecimal('0.999'),'1,00');
assert.equal(P.displayDecimal('0'),'0,00');
assert.equal(P.displayDecimal(null),'—');
assert.throws(()=>P.displayDecimal('-1'));
