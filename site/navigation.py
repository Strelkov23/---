def a(href,label,active=False):
    return '<a href="'+escape(href,quote=True)+'"'+(' aria-current="page"' if active else '')+'>'+escape(label)+'</a>'
def current_group(page):
    for group in GROUPS:
        if page==group[0]+".html":return group
    if page.startswith("indicator-"):return GROUPS[1]
    if page.startswith("sector-") and page!="sector-passports.html":return GROUPS[2]
    return next((g for g in GROUPS if any(href==page for href,_,_ in g[3])),None)
def primary(page):
    group=current_group(page)
    return a("index.html","Главная",page=="index.html")+a("economic-map.html","Карта России",page=="economic-map.html")+a("search.html","Поиск",page=="search.html")+''.join(a(g[0]+".html",g[1],g==group and page!="economic-map.html") for g in GROUPS)
def secondary(page):
    g=current_group(page)
    if not g:return ""
    key,label,_,items=g
    quick=[item for i,item in enumerate(items) if i<3 or item[0]==page]
    rest=[item for item in items if item not in quick]
    links=lambda seq:''.join(a(href,title,href==page) for href,title,_ in seq)
    more='<details class="section-more"><summary>Все инструменты раздела ('+str(len(items))+')</summary><div>'+links(rest)+'</div></details>' if rest else ''
    return '<nav class="section-nav" aria-label="Раздел '+escape(label,quote=True)+'"><span>Раздел: '+a(key+".html",label,page==key+".html")+'</span><div>'+links(quick)+'</div>'+more+'</nav>'
def cards():
    return '<section class="section-directory" aria-label="Разделы портала"><h2>Выберите направление работы</h2><div class="portal-grid">'+''.join('<article><h3>'+a(g[0]+".html",g[1])+'</h3><p>'+escape(g[2])+'</p><p class="portal-quick">'+ ' · '.join(a(h,t) for h,t,_ in g[3][:2])+'</p></article>' for g in GROUPS)+'</div></section>'
def publish(page):
    for key,label,desc,items in GROUPS:
        body='<section class="mast"><p class="kicker">Экономический обзор · раздел</p><h1>'+escape(label)+'</h1><p>'+escape(desc)+'</p></section><section class="portal-grid">'+''.join('<article><h2>'+a(href,title)+'</h2><p>'+escape(note)+'</p></article>' for href,title,note in items)+'</section>'
        page(key+".html",body)

def search_entries():
    entries={}
    for key,label,desc,items in GROUPS:
        entries[key+".html"]={"href":key+".html","title":label,"description":desc,"section":label}
        for href,title,note in items:
            if href not in entries:entries[href]={"href":href,"title":title,"description":note,"section":label}
    return list(entries.values())

