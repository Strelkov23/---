    menu='<nav id="v-section-index" class="v-section-index" aria-label="Содержание страницы"><details open><summary>На этой странице ('+str(len(tasks))+')</summary><ul>'+links+'</ul></details></nav>'
    return body[:first]+menu+body[first:]
