"use strict";
const A=require("node:assert/strict"),V=require("./economic-vector-core.js");
async function run(){
 const index={schema:1,docs:Array.from({length:250},(_,i)=>({kind:"paper",href:"https://doi.org/10.1234/"+i,title:"Research "+i}))};
 index.docs.push({kind:"news",href:"https://example.org/news",title:"News"});
 const parts=Array.from({length:64},(_,i)=>V.targets(index,i));
 A.equal(parts.flat().length,250);
 A.equal(new Set(parts.flat().map(V.identity)).size,250);
 A.ok(parts.every((r,i)=>r.every(d=>V.bucket(d)===i)));
 A.throws(()=>V.targets(index,64));
 A.throws(()=>V.targets({...index,docs:[...index.docs,index.docs[0]]},0));
 const s=parts.findIndex(r=>r.length>1),sha="a".repeat(64),v=Array.from({length:384},(_,i)=>Number(i===0));
 const d=await V.build(index,s,sha,async()=>v);
 A.equal(d.rows.length,parts[s].length);A.ok(V.validate(d,index,sha,s));
 A.throws(()=>V.validate(d,index,"b".repeat(64),s));
 A.throws(()=>V.validate({...d,rows:d.rows.slice(1)},index,sha,s));
 A.throws(()=>V.validate({...d,model:{...d.model,revision:"wrong"}},index,sha,s));
 A.throws(()=>V.validate({...d,rows:d.rows.map((r,i)=>i===0?{...r,title:"Wrong"}:r)},index,sha,s));
 A.throws(()=>V.validate({...d,rows:d.rows.map((r,i)=>i===0?{...r,vector:Array(384).fill(0)}:r)},index,sha,s));
 const r=V.rank(v,[d],index,sha);A.equal(r.searched,d.rows.length);A.equal(r.complete,false);A.equal(r.rows[0].similarity,1);
 A.throws(()=>V.rank(v,[d,d],index,sha));
 const all=await Promise.all(parts.map((_,i)=>V.build(index,i,sha,async()=>v)));
 A.equal(V.rank(v,all,index,sha).complete,true);A.equal(V.rank(v,all,index,sha).searched,250);
 const receipt=x=>({schema:1,source_sha256:sha,shard:x.shard,rows:x.rows.length,file:"research-title-shard-"+String(x.shard).padStart(2,"0")+".json",sha256:"c".repeat(64),bytes:100,model:V.MODEL});
 const pair=x=>({data:x,receipt:receipt(x)});
 const cat=V.catalog(index,sha,[pair(d)]);
 A.equal(cat.complete,false);A.equal(cat.indexed,d.rows.length);A.equal(cat.total,250);A.equal(cat.missing.length,63);A.equal(cat.entries[0].shard,s);
 A.throws(()=>V.catalog(index,sha,[pair(d),pair(d)]));
 A.throws(()=>V.catalog(index,sha,[{data:d,receipt:{...receipt(d),file:"../bad"}}]));
 A.throws(()=>V.catalog(index,sha,[{data:d,receipt:{...receipt(d),rows:0}}]));
 A.throws(()=>V.catalog(index,sha,[{data:d,receipt:{...receipt(d),source_sha256:"b".repeat(64)}}]));
 const complete=V.catalog(index,sha,all.map(pair));
 A.equal(complete.complete,true);A.equal(complete.indexed,250);A.equal(complete.missing.length,0);
 let calls=0;
 const fresh="d".repeat(64),again=await V.build(index,s,fresh,async()=>{calls++;return v},d);
 A.equal(calls,0);A.equal(again.source_sha256,fresh);A.equal(again.rows.length,d.rows.length);
 const altered={...index,docs:index.docs.map(x=>V.identity(x)===V.identity(d.rows[0])?{...x,title:"New title"}:x)};
 const updated=await V.build(altered,s,fresh,async()=>{calls++;return v},d);
 A.equal(calls,1);A.ok(updated.rows.some(x=>x.title==="New title"));
 const reduced={...index,docs:index.docs.filter(x=>V.identity(x)!==V.identity(d.rows[0]))};
 const removed=await V.build(reduced,s,fresh,async()=>{calls++;return v},d);
 A.equal(calls,1);A.equal(removed.rows.length,d.rows.length-1);
 A.throws(()=>V.reusable({...d,model:{...d.model,revision:"wrong"}},s));
 A.throws(()=>V.reusable({...d,rows:[...d.rows,d.rows[0]]},s));
 A.throws(()=>V.reusable(d,(s+1)%64));
 A.throws(()=>V.reusable({...d,rows:d.rows.map(x=>({...x,vector:Array(384).fill(0)}))},s));
 const files=Object.fromEntries(cat.entries.map(e=>[e.file,{sha256:e.sha256,bytes:e.bytes}]));
 const cov=V.validateCatalogue(cat,index,sha,files);
 A.equal(cov.indexed,d.rows.length);A.equal(cov.complete,false);A.equal(cov.total,250);
 A.throws(()=>V.validateCatalogue(cat,index,"b".repeat(64),files));
 A.throws(()=>V.validateCatalogue(cat,index,sha,{}));
 A.throws(()=>V.validateCatalogue({...cat,complete:true},index,sha,files));
 A.throws(()=>V.validateCatalogue({...cat,missing:[]},index,sha,files));
 A.throws(()=>V.validateCatalogue({...cat,indexed:250},index,sha,files));
 const allowed=new Set([V.identity(d.rows[0])]),filtered=V.rankPart(v,d,index,sha,allowed);
 A.equal(filtered.searched,1);A.equal(filtered.rows[0].href,d.rows[0].href);A.equal(filtered.rows[0].similarity,1);
 A.equal(V.rankPart(v,d,index,sha,new Set()).searched,0);
 console.log("53 server vector and browser catalogue checks passed");
}
module.exports=run;
if(require.main===module)run().catch(e=>{console.error(e);process.exitCode=1;});
