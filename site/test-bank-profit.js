const assert=require('node:assert/strict'),P=require('./bank-profit.js');
assert.equal(P.change('120','100'),20);assert.equal(P.change('-20','100'),-120);assert.equal(P.change('20','-100'),null);assert.equal(P.change('20',null),null);
assert.equal(P.fee({fee_income:'9007199254740993',fee_expense:'1'}),'9007199254740992');assert.equal(P.fee({fee_income:'1',fee_expense:null}),null);
assert.deepEqual(P.compare([{registration_number:'1',current:{profit:null}},{registration_number:'2',current:{profit:'-5'}},{registration_number:'3',current:{profit:'0'}}],'profit').map(r=>r.registration_number),['3','2','1']);

const sp=P.specs[0];
assert.equal(P.ratio({interest_expense:'1',interest_income:'3'},sp),'3333');
assert.equal(P.ratio({interest_expense:'1',interest_income:'0'},sp),null);
assert.equal(P.ratio({interest_expense:'-1',interest_income:'3'},sp),null);
assert.equal(P.ratio({interest_expense:null,interest_income:'3'},sp),null);
assert.equal(P.ratio({net_interest:'-1',interest_income:'3'},P.specs[3]),'-3333');
assert.equal(P.ratio({interest_expense:'9007199254740993',interest_income:'9007199254740993'},sp),'10000');
assert.equal(P.percent('-1'),'−0,01');
assert.equal(P.transition('10','-2'),'loss_profit');
assert.equal(P.transition('-1','10'),'profit_loss');
assert.equal(P.transition('0','0'),'zero_zero');
assert.equal(P.transition(null,'0'),'missing');
const d={cohort:['1','2','3'],rows:[{registration_number:'1',current:{profit:'9007199254740993',interest_expense:'1',interest_income:'4'},prior:{profit:'2',interest_expense:'1',interest_income:'2'}},{registration_number:'2',current:{profit:'-3'},prior:{profit:'4'}},{registration_number:'3',current:{profit:'10'},prior:{profit:null}},{registration_number:'4',current:{profit:'20'},prior:{profit:'10'}}]};
